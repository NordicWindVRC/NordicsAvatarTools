using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Unity.Collections;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;

namespace NordicWind.SubmeshSplitter.Editor
{
    internal static class SplitMeshGenerator
    {
        // Set under Edit > Project Settings > NordicWind.
        internal static string AssetFolder => NordicWindSettings.FolderFor("SubmeshSplitter");

        // Only rename GameObjects; never replace renderers or mesh assets.
        // This keeps Meshia / AAO component references and prefab overrides intact.
        internal static string GeneratedRendererName(SkinnedMeshRenderer source, int index)
        {
            var materials = source.sharedMaterials;
            string materialName = index < materials.Length && materials[index] != null
                ? materials[index].name : "NoMaterial";
            var invalid = System.IO.Path.GetInvalidFileNameChars();
            var cleaned = new StringBuilder(materialName.Length);
            foreach (char c in materialName)
                cleaned.Append(c == '/' || c == '\\' || char.IsControl(c) || Array.IndexOf(invalid, c) >= 0 ? '_' : c);
            string suffix = cleaned.ToString().Trim().TrimEnd('.');
            if (string.IsNullOrEmpty(suffix)) suffix = "NoMaterial";
            return "Submesh_" + index + "_" + suffix;
        }

        // Requirements for generating. Other components on the source object are fine:
        // general tools act on the original renderer; only its mesh must stay untouched
        // until reassembly, which the build checks separately.
        internal static string ValidateSource(NordicsSubmeshSplitter splitter)
        {
            if (splitter == null) return "Missing splitter.";
            var renderer = splitter.GetComponent<SkinnedMeshRenderer>();
            if (renderer == null || renderer.sharedMesh == null) return "A source SkinnedMeshRenderer with a mesh is required.";
            var mesh = renderer.sharedMesh;
            if (!mesh.isReadable) return "Source mesh is not readable. Enable Read/Write in the mesh import settings.";
            if (mesh.subMeshCount < 1) return "Mesh has no submeshes.";
            for (int i = 0; i < mesh.subMeshCount; i++)
                if (mesh.GetTopology(i) != MeshTopology.Triangles) return $"Submesh {i} does not use triangle topology.";
            if (renderer.sharedMaterials.Length < mesh.subMeshCount)
                return "Source has fewer material slots than submeshes.";
            return null;
        }

        // Checks that a generated split still matches its source. Used by the inspector
        // and, at NDMF Resolving, by the build (where a mismatch stops the build).
        internal static string ValidateGenerated(NordicsSubmeshSplitter splitter)
        {
            var source = splitter.GetComponent<SkinnedMeshRenderer>();
            if (source == null || source.sharedMesh == null) return "The source SkinnedMeshRenderer or its mesh is missing.";
            if (!splitter.hasGenerated) return "Split meshes have not been generated.";
            var data = splitter.assetData;
            if (data == null) return "The split mesh asset is missing. Update split meshes.";
            if (splitter.generatedRoot == null || !splitter.generatedRoot.IsChildOf(splitter.transform))
                return "The split mesh container is missing or no longer under the source object. Update split meshes.";
            int count = source.sharedMesh.subMeshCount;
            if (splitter.generatedRenderers == null || splitter.generatedRenderers.Count != count || data.meshes.Count != count)
                return $"The source has {count} submeshes but the split has {splitter.generatedRenderers?.Count ?? 0}. Update split meshes.";
            for (int i = 0; i < count; i++)
            {
                var part = splitter.generatedRenderers[i];
                if (part == null || !part.transform.IsChildOf(splitter.generatedRoot))
                    return $"Split renderer {i} is missing or was moved out of the split container. Update split meshes.";
                if (part.sharedMesh == null || part.sharedMesh != data.meshes[i])
                    return $"Split renderer '{part.name}' does not use its generated mesh. Update split meshes.";
            }
            if (string.IsNullOrEmpty(data.sourceFingerprint))
                return "The split was generated by an older version. Update split meshes.";
            var fingerprint = SplitSourceInfo.Fingerprint(source.sharedMesh);
            if (fingerprint == null) return "The source mesh is not readable. Enable Read/Write in the mesh import settings.";
            if (fingerprint != data.sourceFingerprint)
                return "The source mesh changed after the split was generated. Update split meshes.";
            return null;
        }

        internal static string SharedVertexWarning(Mesh mesh)
        {
            int shared = SplitSourceInfo.SharedVertexCount(mesh);
            return shared == 0 ? null
                : $"{shared} vertices are shared between submeshes. Each part gets its own copy, " +
                  "so processing parts differently (for example simplifying them) can open seams along those borders.";
        }

        // Clone-and-isolate: keep the source vertex buffers, skinning, bindposes,
        // vertex order, and every blendshape frame intact. Only the index buffer
        // and submesh descriptors change. This deliberately retains unreferenced
        // vertices; processors may compact them later.
        private static void ExtractAll(NordicsSubmeshSplitter splitter, Mesh source, List<Mesh> output)
        {
            for (int i = 0; i < source.subMeshCount; i++)
            {
                ProgressOrCancel("Cloning and isolating submeshes", i, source.subMeshCount);
                var isolated = UnityEngine.Object.Instantiate(source);
                isolated.name = source.name + "_Submesh_" + i;
                // Cache indices before changing the clone's submesh count.
                int[] indices = source.GetIndices(i);
                isolated.subMeshCount = 1;
                isolated.SetIndices(indices, MeshTopology.Triangles, 0, false);
                // No RecalculateBounds: the source's original bounds are retained.
                output.Add(isolated);
            }

        }

        private static void ProgressOrCancel(string label, int current, int total)
        {
            if (EditorUtility.DisplayCancelableProgressBar("Nordic's Submesh Splitter", label,
                Mathf.Clamp01((float)current / Math.Max(1, total))))
                throw new OperationCanceledException("Mesh generation cancelled; existing assets were not changed.");
        }

        private static void EnsureFolder() => NordicWindSettings.EnsureFolder(AssetFolder);

        private static void ValidateNativeVertexBuffers(Mesh mesh, int submeshIndex)
        {
            for (int stream = 0; stream < 4; stream++)
            {
                int stride = mesh.GetVertexBufferStride(stream);
                if (stride == 0) continue;
                using (var buffer = mesh.GetVertexBuffer(stream))
                {
                    if (buffer == null || buffer.stride != stride || buffer.count != mesh.vertexCount)
                        throw new InvalidOperationException(
                            "Generated submesh " + submeshIndex + " has inconsistent native vertex buffer " +
                            stream + ": vertexCount=" + mesh.vertexCount + ", meshStride=" + stride +
                            ", bufferStride=" + (buffer == null ? -1 : buffer.stride) +
                            ", bufferCount=" + (buffer == null ? -1 : buffer.count) + ".");
                }
            }
        }

        // A container is reused only when this splitter owns it: same owning asset, same
        // splitter identity, and no other splitter in the same prefab or scene uses it.
        // Duplicated splitters (Ctrl+D copies splitterId) get a fresh identity instead.
        private static bool OwnsContainer(NordicsSubmeshSplitter splitter, SplitContext context)
        {
            var others = SplittersIn(context, splitter).Where(s => s != splitter).ToList();
            if (string.IsNullOrEmpty(splitter.splitterId) || others.Any(s => s.splitterId == splitter.splitterId))
            {
                Undo.RecordObject(splitter, "Assign splitter identity");
                splitter.splitterId = Guid.NewGuid().ToString("N");
            }
            var data = splitter.assetData;
            return data != null && data.ownerAssetGuid == context.OwnerGuid
                   && data.ownerObjectId == splitter.splitterId
                   && others.All(s => s.assetData != data);
        }

        private static IEnumerable<NordicsSubmeshSplitter> SplittersIn(SplitContext context, NordicsSubmeshSplitter splitter)
        {
            if (context.SearchRoot != null)
                return context.SearchRoot.GetComponentsInChildren<NordicsSubmeshSplitter>(true);
            return splitter.gameObject.scene.GetRootGameObjects()
                .SelectMany(root => root.GetComponentsInChildren<NordicsSubmeshSplitter>(true));
        }

        internal static void Generate(NordicsSubmeshSplitter splitter)
        {
            var context = SplitContext.Resolve(splitter);
            if (!context.CanGenerate) throw new InvalidOperationException(context.Message);
            var error = ValidateSource(splitter);
            if (error != null) throw new InvalidOperationException(error);
            var sourceRenderer = splitter.GetComponent<SkinnedMeshRenderer>();
            var source = sourceRenderer.sharedMesh;
            int count = source.subMeshCount;
            bool ownAsset = OwnsContainer(splitter, context);
            var old = splitter.assetData;

            // Parts beyond the new submesh count are removed. Parts inherited from a base
            // prefab cannot be deleted in a variant, so that case must be fixed in the base.
            var extraParts = splitter.generatedRenderers.Skip(count).Where(r => r != null).ToList();
            var inherited = extraParts.FirstOrDefault(r => PrefabUtility.IsPartOfPrefabInstance(r.gameObject));
            if (inherited != null)
                throw new InvalidOperationException(
                    $"The source now has {count} submeshes, but split renderer '{inherited.name}' is inherited from " +
                    $"'{PrefabUtility.GetPrefabAssetPathOfNearestInstanceRoot(inherited.gameObject)}'. Update the split in that prefab first.");

            // Construct and validate everything before changing persistent objects.
            var fresh = new List<Mesh>();
            var supersededMeshes = new List<Mesh>();
            try
            {
                ExtractAll(splitter, source, fresh);
                ProgressOrCancel("Calculating source fingerprint", 0, 1);
                string fingerprint = SplitSourceInfo.ComputeFingerprint(source);
                ProgressOrCancel("Saving generated assets", 0, 1);
                EnsureFolder();
                if (!ownAsset)
                {
                    string path = AssetDatabase.GenerateUniqueAssetPath(AssetFolder + "/" + splitter.name + "_SplitMeshes.asset");
                    var data = ScriptableObject.CreateInstance<NordicsSubmeshAssetData>();
                    data.name = splitter.name + "_SplitMeshes";
                    data.ownerAssetGuid = context.OwnerGuid; data.ownerObjectId = splitter.splitterId;
                    AssetDatabase.CreateAsset(data, path);
                    foreach (var mesh in fresh)
                    {
                        mesh.hideFlags = HideFlags.HideInHierarchy;
                        AssetDatabase.AddObjectToAsset(mesh, data);
                        data.meshes.Add(mesh);
                    }
                    data.sourceFingerprint = fingerprint;
                    EditorUtility.SetDirty(data);
                    Undo.RecordObject(splitter, "Assign split mesh assets");
                    splitter.assetData = data;
                }
                else
                {
                    // Do not CopySerialized into an existing Mesh. Unity may retain the old
                    // native GraphicsBuffer allocations when vertex count/layout changes.
                    // Add the replacement meshes as new sub-assets, then redirect renderers.
                    // Existing GameObjects and SkinnedMeshRenderer identities stay intact.
                    Undo.RecordObject(old, "Replace split mesh references");
                    for (int i = 0; i < fresh.Count; i++)
                    {
                        var replacement = fresh[i];
                        replacement.hideFlags = HideFlags.HideInHierarchy;
                        AssetDatabase.AddObjectToAsset(replacement, old);
                        if (i < old.meshes.Count)
                        {
                            if (old.meshes[i] != null) supersededMeshes.Add(old.meshes[i]);
                            old.meshes[i] = replacement;
                        }
                        else old.meshes.Add(replacement);
                    }
                    for (int i = fresh.Count; i < old.meshes.Count; i++)
                        if (old.meshes[i] != null) supersededMeshes.Add(old.meshes[i]);
                    if (old.meshes.Count > fresh.Count) old.meshes.RemoveRange(fresh.Count, old.meshes.Count - fresh.Count);
                    old.sourceFingerprint = fingerprint;
                    EditorUtility.SetDirty(old);
                }
                if (splitter.generatedRoot == null)
                {
                    var go = new GameObject("Nordic_SplitMeshes");
                    Undo.RegisterCreatedObjectUndo(go, "Create split mesh container");
                    go.transform.SetParent(splitter.transform, false);
                    Undo.RecordObject(splitter, "Assign split mesh container");
                    splitter.generatedRoot = go.transform;
                }
                foreach (var extra in extraParts)
                    Undo.DestroyObjectImmediate(extra.gameObject);
                if (splitter.generatedRenderers.Count > count)
                {
                    Undo.RecordObject(splitter, "Remove split renderers");
                    splitter.generatedRenderers.RemoveRange(count, splitter.generatedRenderers.Count - count);
                }
                // Keep inherited child identities and all user-added components.
                for (int i = 0; i < count; i++)
                {
                    SkinnedMeshRenderer renderer = i < splitter.generatedRenderers.Count ? splitter.generatedRenderers[i] : null;
                    if (renderer == null)
                    {
                        var go = new GameObject(GeneratedRendererName(sourceRenderer, i));
                        Undo.RegisterCreatedObjectUndo(go, "Create split renderer");
                        go.transform.SetParent(splitter.generatedRoot, false);
                        renderer = Undo.AddComponent<SkinnedMeshRenderer>(go);
                        Undo.RecordObject(splitter, "Assign split renderer");
                        if (i < splitter.generatedRenderers.Count) splitter.generatedRenderers[i] = renderer;
                        else splitter.generatedRenderers.Add(renderer);
                    }
                    // Names follow the source's current material; identities are kept.
                    string expectedName = GeneratedRendererName(sourceRenderer, i);
                    if (renderer.gameObject.name != expectedName)
                    {
                        Undo.RecordObject(renderer.gameObject, "Rename split renderer");
                        renderer.gameObject.name = expectedName;
                        PrefabUtility.RecordPrefabInstancePropertyModifications(renderer.gameObject);
                    }
                    Undo.RecordObject(renderer, "Update split renderer");
                    renderer.sharedMesh = splitter.assetData.meshes[i];
                    ValidateNativeVertexBuffers(renderer.sharedMesh, i);
                    // The source owns materials; the part only mirrors its slot for the editor
                    // preview. The build always takes materials from the source renderer.
                    renderer.sharedMaterials = new[] { sourceRenderer.sharedMaterials[i] };
                    renderer.bones = sourceRenderer.bones;
                    renderer.rootBone = sourceRenderer.rootBone;
                    renderer.localBounds = sourceRenderer.localBounds;
                    renderer.quality = sourceRenderer.quality;
                    renderer.updateWhenOffscreen = sourceRenderer.updateWhenOffscreen;
                    renderer.shadowCastingMode = sourceRenderer.shadowCastingMode;
                    renderer.receiveShadows = sourceRenderer.receiveShadows;
                    renderer.lightProbeUsage = sourceRenderer.lightProbeUsage;
                    renderer.reflectionProbeUsage = sourceRenderer.reflectionProbeUsage;
                    renderer.probeAnchor = sourceRenderer.probeAnchor;
                    renderer.enabled = true;
                    // Transfer initial weights by name; indices match the source today but names are robust.
                    var generatedMesh = renderer.sharedMesh;
                    for (int b = 0; b < generatedMesh.blendShapeCount; b++)
                    {
                        int sourceIndex = source.GetBlendShapeIndex(generatedMesh.GetBlendShapeName(b));
                        if (sourceIndex >= 0)
                            renderer.SetBlendShapeWeight(b, sourceRenderer.GetBlendShapeWeight(sourceIndex));
                    }
                    PrefabUtility.RecordPrefabInstancePropertyModifications(renderer);
                }
                Undo.RecordObject(splitter, "Update splitter metadata");
                if (!splitter.hasGenerated) splitter.originalRendererWasEnabled = sourceRenderer.enabled;
                splitter.hasGenerated = true;
                // Source geometry stays untouched; hide only the editor renderer to prevent duplicate rendering.
                Undo.RecordObject(sourceRenderer, "Hide original renderer");
                sourceRenderer.enabled = false;
                PrefabUtility.RecordPrefabInstancePropertyModifications(sourceRenderer);
                PrefabUtility.RecordPrefabInstancePropertyModifications(splitter);
                AssetDatabase.SaveAssets();
                // Remove superseded mesh sub-assets only after the replacement references
                // have been serialized. This intentionally changes Mesh object identity.
                foreach (var previous in supersededMeshes)
                {
                    if (previous == null) continue;
                    AssetDatabase.RemoveObjectFromAsset(previous);
                    UnityEngine.Object.DestroyImmediate(previous, true);
                }
                if (supersededMeshes.Count != 0) AssetDatabase.SaveAssets();
                EditorSceneManager.MarkSceneDirty(splitter.gameObject.scene);
            }
            finally
            {
                EditorUtility.ClearProgressBar();
                // Fresh meshes are assets in the new-owner case; destroy only temporary meshes.
                foreach (var mesh in fresh)
                    if (mesh != null && !EditorUtility.IsPersistent(mesh)) UnityEngine.Object.DestroyImmediate(mesh);
            }
        }
    }
}
